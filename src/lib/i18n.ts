const dictionaries: Record<Language, Record<string, string>> = { tr, en, de, fr };

export function translate(key: string, language: Language) {
  return dictionaries[language]?.[key] ?? tr[key] ?? key;
}

export function useT() {
  const language = useApp((state) => state.language);
  return useCallback((key: string) => translate(key, language), [language]);
}
